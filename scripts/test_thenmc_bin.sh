LUMINA_BF_OPACITY=1 LUMINA_CMFGEN_SIGMA_BF=$MODEL/cmfgen_sigma_bf.bin
LUMINA_DYNAMIC_TRANSPROB=1 LUMINA_NLTE_SKIP_Z=14 LUMINA_NLTE_START_ITER=2
