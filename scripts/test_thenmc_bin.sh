OUT=/tmp/claude-10396/-home-kjhan-BACKUP-Eunha-A1-Claude-Lumina-sn/f5549e0b-f5d0-4d4a-8024-0bb561d5a21d/scratchpad/bisect_$(basename $BIN).log
