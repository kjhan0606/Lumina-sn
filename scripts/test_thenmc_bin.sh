LUMINA_COUPLED_LAMBDA_STAR=1 LUMINA_COUPLED_TDEP=1 LUMINA_RADEQ_LINE_RE=0
LUMINA_TE_TRAD_RATIO=1.0 LUMINA_LINE_INTERACTION=macroatom LUMINA_TAU_BY_ION=1
LUMINA_DIFFUSE_INNER_BC=1 LUMINA_ENERGY_BUDGET=1 LUMINA_NLTE_LTE_FLOOR=1
LUMINA_NLTE_COLL_FIX=1 LUMINA_NLTE_ION_LOCK=1 LUMINA_NLTE_LOCK_START_ITER=0
