    libs=["-L.","-L"+str(native/"lib"),"-lsubs","-lpgplt","-lmod",native/"lib/libmy_lapack.a",native/"lib/libmy_blas.a"]
    command(["gfortran","-fopenmp","-m64",native/"new_main/cmfgen.o","cmfgen_sub.o",*common,*libs,"-o","cmfgen_sweep.exe"],out)
    command(["gfortran","-fopenmp","-m64","sweep_mom_replay.o",*common,*libs,"-o","sweep_mom_replay.exe"],out)
    outputs=[out/name for name in sources]+[out/"libsubs.a",out/"cmfgen_sweep.exe",out/"sweep_mom_replay.exe"]
    result=dict(scope="전체 실제 첫 주파수부터의 수리 연결 진단; 인구/T 갱신 없음",parent=str(parent),
        formal_build=str(formal),mom_build=str(mom),native=str(native),parent_manifest_sha256=sha(parent/"affine-build.json"),
        rebuilt_unmodified_sha256=record["rebuilt_unmodified_sha256"],generator_sha256=sha(Path(__file__)),
        output_sha256={str(p):sha(p) for p in outputs},capture_event=capture_event,nonfatal_psd=nonfatal_psd,accelerate_late=accelerate_late,final_goal="NOT_JUDGED")
    with (out/"sweep-build.json").open("x") as f:json.dump(result,f,ensure_ascii=False,indent=2)
    print(json.dumps(dict(build=str(out),outputs=len(outputs))))


