    main=once(main,"10000\tCONTINUE\n", "\tCALL LUMINA_WHOLE_FREQUENCY_END(ML,NCF)\n10000\tCONTINUE\n")
    fdiag=(formal/"lumina_formal_diag.f90").read_text().replace("IF(A%INITIALIZE.OR.A%INNER_BND_METH/='DIFFUSION')STOP 89","IF(A%INNER_BND_METH/='DIFFUSION')STOP 89")
    sources={"lumina_affine_boundary.f90":aff,"lumina_mom_diag.f90":diag,"lumina_formal_diag.f90":fdiag,
             "lumina_whole_monitor.f90":monitor_source(capture_event,nonfatal_psd),"mom_jrel_v9.f":body,"cmf_formal_rel_v4.f":fg,
             "comp_j_blank.f":caller,"cmfgen_sub.f":main,"sweep_mom_replay.f90":exact_replay_source()}
    if accelerate_late:
        sources={"cmfgen_mom_acceleration.f90":Path(__file__).with_name('cmfgen_mom_acceleration.f90').read_text(),**sources}
        sources['mom_jrel_v9.f']=accelerate_moment(body)
        monitor=sources['lumina_whole_monitor.f90']
