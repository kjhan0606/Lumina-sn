def prepare(parent,out,capture_event=False,nonfatal_psd=False,accelerate_late=False):
    if out.exists():raise ValueError("기존 sweep build 보존")
    record=json.loads((parent/"affine-build.json").read_text())
    if not record["spatial_affine"]:raise ValueError("공간/입사 경계 수리본이 아님")
    for name,expected in record["output_sha256"].items():
        if sha(Path(name))!=expected:raise ValueError("수리 부모 source/exe 변경")
    formal=Path(record["formal_build"]);mom=Path(record["mom_build"]);native=Path(record["native"])
    out.mkdir()
    diag=(mom/"lumina_mom_diag.f90").read_text()
    diag=once(diag,"CALL LUMINA_SNAPSHOT_IO('MOM_CAPTURE.bin',A,J,R,.FALSE.)\n",
              "CALL LUMINA_WHOLE_EVENT_HOOK()\nCALL LUMINA_SNAPSHOT_IO('MOM_CAPTURE.bin',A,J,R,.FALSE.)\n")
    diag=once(diag,"IF(MODE=='CAPTURE_FIRST')THEN\n", "IF(MODE=='CAPTURE_FIRST')THEN\n CALL LUMINA_WHOLE_FINISH()\n")
    body=(parent/"mom_jrel_v9.f").read_text()
    body=once(body,"\tUSE LUMINA_AFFINE_BOUNDARY,ONLY:","\tUSE LUMINA_WHOLE_MONITOR\n\tUSE LUMINA_AFFINE_BOUNDARY,ONLY:")
    names=",".join(name for name,_,_ in ARGUMENTS)
    body=once(body,"\t CALL LUMINA_TAKE_ARGS(LUM_A,"+names+")\n", "\t CALL LUMINA_TAKE_ARGS(LUM_A,"+names+")\n\t CALL WM_BEGIN_MOM()\n")
    body=once(body,"\tCALL GET_MOMS_REL(R, V, FREQ, N_TYPE, ND)\n",
              "\tCALL GET_MOMS_REL(R, V, FREQ, N_TYPE, ND)\n\tCALL WM_SAVE_PHYSICAL_CLOSURE()\n")
    marker="\tIF(LUM_SELECTED)THEN\n\t CALL LUMINA_JREL_TAKE(LUM_JK)\n"
    check="""\tIF(WHOLE_ENABLED())THEN
\t WM_A=LUM_A
\t CALL WM_CHECK(FREQ,INIT,INCL_ADVEC_TERMS,ICOUNT,LUM_TRI,LUM_RAW,GAM_RSQHNU,LUM_SLOPE,LUM_AFFINE_FLUX_SOURCE,LUM_BAD,LUM_I)
\t CALL WM_KEEP(LUM_BAD,LUM_I,ICOUNT,LUM_INITIAL_PENDING,LUM_A,LUM_J,LUM_R,LUM_JK,LUM_RK,LUM_TRI,LUM_RAW,GAM_RSQHNU,LUM_SLOPE)
\tEND IF
"""
    body=once(body,marker,check+marker)
    aff=(parent/"lumina_affine_boundary.f90").read_text()
    aff=once(aff,"LOGICAL,SAVE::AFFINE_READY", "REAL(KIND=LDP),SAVE::AFFINE_JMIN=0.0_LDP,AFFINE_JPLUS=0.0_LDP\nLOGICAL,SAVE::AFFINE_READY")
    aff=once(aff," IF(.NOT.AFFINE_READY.OR.FREQ>AFFINE_FREQ_SAVE)STOP 89", " IF(.NOT.AFFINE_READY.OR.FREQ>AFFINE_FREQ_SAVE)THEN\n  CALL LUMINA_WHOLE_FORMAL_ERROR(1)\n  RETURN\n END IF")
    aff=once(aff,"IF(JP<=0.0_LDP.OR.JM<0.0_LDP)STOP 89", "IF(JP<=0.0_LDP.OR.JM<0.0_LDP)THEN\n CALL LUMINA_WHOLE_FORMAL_ERROR(2)\n RETURN\nEND IF")
    aff=once(aff,"IF(.NOT.ALL(IEEE_IS_FINITE([JP,HP,NNP,JM,HM,NNM])))STOP 89", "IF(.NOT.ALL(IEEE_IS_FINITE([JP,HP,NNP,JM,HM,NNM])))THEN\n CALL LUMINA_WHOLE_FORMAL_ERROR(3)\n RETURN\nEND IF")
    aff=once(aff,"HBC=HP/JP;NBC=NNP/JP", "AFFINE_JMIN=JM;AFFINE_JPLUS=JP\nHBC=HP/JP;NBC=NNP/JP")
    fg=(parent/"cmf_formal_rel_v4.f").read_text()
    fg=once(fg,"\tUSE LUMINA_FORMAL_DIAG\n", "\tUSE LUMINA_FORMAL_DIAG\n\tUSE LUMINA_WHOLE_MONITOR,ONLY:WM_FORMAL_CHECK,WM_REMEMBER_FORMAL_INPUT\n")
    fnames=",".join(name for name,_,_ in ARGS)
    fg=once(fg,"\tIF(INITIALIZE)THEN\n\t  NU_ON_dNU=0.0_LDP", "\tCALL WM_REMEMBER_FORMAL_INPUT("+fnames+")\n\tIF(INITIALIZE)THEN\n\t  NU_ON_dNU=0.0_LDP")
    fg=once(fg,"\tFIRST_TIME=.FALSE.\n", "\tCALL WM_FORMAL_CHECK("+fnames+")\n\tFIRST_TIME=.FALSE.\n")
    caller=(formal/"comp_j_blank.f").read_text()
    caller=once(caller,"\tUSE SET_KIND_MODULE\n", "\tUSE SET_KIND_MODULE\n\tUSE LUMINA_WHOLE_MONITOR,ONLY:WM_NOTE_F,WM_SAVE_LOOP\n")
    marker="\t       CALL MOM_JREL_V9(TA,CHI_CLUMP,CHI_SCAT_CLUMP,V,SIGMA,R,\n"
    caller=once(caller,marker,"\t       IF(COHERENT_ES)THEN\n\t        CALL WM_SAVE_LOOP(J_IT_COUNTER,FOLD,ACC_EDD_FAC,COMPUTE_EDDFAC,COHERENT_ES,ETA_CLUMP,CHI_SCAT_CLUMP,ETA_CLUMP,ND)\n\t       ELSE\n\t        CALL WM_SAVE_LOOP(J_IT_COUNTER,FOLD,ACC_EDD_FAC,COMPUTE_EDDFAC,COHERENT_ES,ETA_CLUMP,CHI_SCAT_CLUMP,RJ_ES,ND)\n\t       END IF\n"+marker)
    marker="C Output RJ for subsequent iterations.\nC\n\t    WRITE(LU_EDD,REC=ACCESS_F)(RJ(I),I=1,ND),FL\n"
    caller=once(caller,marker,"C Output RJ for subsequent iterations.\nC\n\t    CALL WM_NOTE_F(J_IT_COUNTER,T1,ACC_EDD_FAC)\n\t    WRITE(LU_EDD,REC=ACCESS_F)(RJ(I),I=1,ND),FL\n")
