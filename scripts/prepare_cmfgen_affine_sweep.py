    for name in sources:
        flags=FLAGS if name.endswith(".f") else ["-fopenmp","-m64","-O","-ffree-line-length-none","-fbacktrace"]
        command(["gfortran",*flags,"-I.","-I"+str(formal),"-I"+str(mom),"-I"+str(native/"mod"),"-c",name],out)
    shutil.copy2(parent/"libsubs.a",out/"libsubs.a")
    command(["ar","r","libsubs.a","mom_jrel_v9.o","cmf_formal_rel_v4.o","comp_j_blank.o"],out)
    common=["lumina_affine_boundary.o","lumina_mom_diag.o","lumina_formal_diag.o","lumina_whole_monitor.o",formal/"ext_rel_grid_v4.o",mom/"mod_jrel_v9.o"]
